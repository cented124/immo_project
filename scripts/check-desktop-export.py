"""Check a synthetic desktop export and import it into a disposable native DB."""

import json
import os
from pathlib import Path
import sys
import tempfile
import zipfile

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "backend"))
with tempfile.TemporaryDirectory(prefix="export-check-", dir=root / ".runtime") as tmp:
    folder = Path(tmp)
    with zipfile.ZipFile(sys.argv[1]) as archive:
        names = archive.namelist()
        for name in [
            "STARTEN.cmd",
            "SICHERN.cmd",
            "scripts/desktop.py",
            ".github/workflows/windows.yml",
        ]:
            assert "Raumwerk/" + name in names, name
        assert not any(
            n.endswith(("/.env", "/app.db", "/encryption.key")) or "/DATEN/" in n
            for n in names
        )
        seed = json.loads(archive.read("Raumwerk/project/project.json"))
        assert seed["published"]["company"] == "Fensterblick Test GmbH"
        assert len(seed["properties"]) == 1
        assert not seed["published"]["modules"]["telegram"]
        assert b"FAKE-LOCAL-NO-SENDING" not in archive.read(
            "Raumwerk/project/project.json"
        )
        # This archive was generated by this test's own authenticated application.
        archive.extractall(folder)
    os.environ["DATA_DIR"] = str(folder / "data")
    os.environ["DATABASE_URL"] = "sqlite:///" + (folder / "data/app.db").as_posix()
    os.environ.pop("ENCRYPTION_KEY", None)
    from alembic import command
    from alembic.config import Config
    from app.db import Session, Setting, Property, User, Inquiry, Delivery, File, engine
    from app.project import import_project
    from sqlalchemy import select, func

    config = Config(str(root / "backend/alembic.ini"))
    command.upgrade(config, "head")
    project = folder / "Raumwerk/project/project.json"
    try:
        assert import_project(project)
        assert not import_project(project)
        with Session() as db:
            assert (
                db.get(Setting, "published").value["company"]
                == "Fensterblick Test GmbH"
            )
            assert db.scalar(select(func.count()).select_from(Property)) == 1
            for model in [User, Inquiry, Delivery]:
                assert db.scalar(select(func.count()).select_from(model)) == 0
            for row in db.scalars(select(File)):
                assert (folder / "data/files" / row.id).is_file()
    finally:
        engine.dispose()
print(
    "Native project export and isolated seed import passed; no accounts or inquiries exported."
)
